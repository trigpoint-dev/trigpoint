def run_git(root: Path, *args: str) -> str:
    cmd = [
        "git",
        "-c",
        "user.name=t",
        "-c",
        "user.email=t@example.com",
        "-c",
        "commit.gpgsign=false",
        *args,
    ]
    proc = subprocess.run(cmd, cwd=root, capture_output=True, text=True, check=True)  # noqa: S603
    return proc.stdout.strip()
